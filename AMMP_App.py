    "    bo = ls_info['Bo']            # m3 CH4 / kg VS\n",
    "    \n",
    "    # Calculate Total Annual Volatile Solids (kg VS / yr)\n",
    "    total_vs_annual = num_head * vs_per_head * 365\n",
    "    \n",
    "    # Baseline MCF (Methane Conversion Factor)\n",
    "    # Lagoon/Flush baseline MCF approximation: ~0.70 (70%)\n",
    "    baseline_mcf = 0.70\n",
    "    \n",
    "    # Proposed Practice MCF lookup\n",
    "    practice = inputs['proposed_practice']\n",
    "    if 'Pasture' in practice:\n",
    "        proposed_mcf = 0.015\n",
    "    elif 'composting' in practice or 'bedded pack' in practice:\n",
    "        proposed_mcf = 0.010\n",
    "    elif 'solar drying' in practice or 'daily spread' in practice:\n",
    "        proposed_mcf = 0.005\n",
    "    else:\n",
    "        proposed_mcf = 0.040\n",
    "        \n",
    "    # Solid Separation Adjustment\n",
    "    sep_eff = REF['sep_eff'].get(inputs['solid_separator'], 0.0)\n",
    "    if inputs['flocculant'] != 'No':\n",
    "        sep_eff = min(0.80, sep_eff * 1.3)\n",
    "        \n",
    "    # Baseline CH4 Emissions (MT CH4 / yr)\n",
    "    # CH4 (kg) = Total_VS * Bo * 0.67 * MCF\n",
    "    ch4_baseline_kg = total_vs_annual * bo * 0.67 * baseline_mcf\n",
    "    ch4_baseline_mt = ch4_baseline_kg / 1000.0\n",
    "    \n",
    "    # Project CH4 Emissions (MT CH4 / yr)\n",
    "    # Separated fraction goes to dry practice; liquid fraction reduced\n",
    "    vs_liquid = total_vs_annual * (1.0 - sep_eff)\n",
    "    vs_solid = total_vs_annual * sep_eff\n",
    "    \n",
    "    ch4_project_liquid = vs_liquid * bo * 0.67 * baseline_mcf * (1.0 - inputs['flush_reduction_pct'])\n",
    "    ch4_project_solid = vs_solid * bo * 0.67 * proposed_mcf\n",
    "    \n",
    "    ch4_project_mt = (ch4_project_liquid + ch4_project_solid) / 1000.0\n",
