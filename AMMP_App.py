    "    co2e_project = ch4_project_mt * gwp_ch4\n",
    "    co2e_reduction_annual = max(0.0, co2e_baseline - co2e_project)\n",
    "    co2e_reduction_10yr = co2e_reduction_annual * 10.0\n",
